// TestPatchKustomize_AFileThatIsThere: the four states of a patch file and
// its entry in the list. A workload is done only when the two are there.
func TestPatchKustomize_AFileThatIsThere(t *testing.T) {
	t.Parallel()
	root := patchTree(t)
	patchPath := func(dir string) string { return filepath.Join(dir, webPatchName) }
	listPath := func(dir string) string { return filepath.Join(dir, "kustomization.yaml") }

	t.Run("the file is there and the list does not name it", func(t *testing.T) {
		t.Parallel()
		// A person removed the entry and kept the file, or a run stopped
		// before it wrote the list. A build does not use the file.
		dir := writeManifests(t, map[string]string{webPatchName: webPatch, "kustomization.yaml": listOf(t, "pod_other.yaml"), "pod_other.yaml": "x\n"})
		res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
		if len(res.Spec.Files) != 1 || res.Spec.Files[0].Path != listPath(dir) || res.Spec.Files[0].Created {
			t.Errorf("files = %+v; want only the list, as a changed file", res.Spec.Files)
		}
		if changeOf(t, res, "web").Status != schema.PatchStatusPatched {
			t.Errorf("web = %+v", changeOf(t, res, "web"))
		}
		wantFile(t, listPath(dir), listOf(t, "pod_other.yaml")+"- path: "+webPatchName+"\n", "the list")
	})

	t.Run("the list names the file and the file is not there", func(t *testing.T) {
		t.Parallel()
		dir := writeManifests(t, map[string]string{"kustomization.yaml": listOf(t, webPatchName)})
		res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
		if len(res.Spec.Files) != 1 || res.Spec.Files[0].Path != patchPath(dir) || !res.Spec.Files[0].Created {
			t.Errorf("files = %+v; want only the patch file", res.Spec.Files)
		}
		wantFile(t, patchPath(dir), webPatch, "the patch file")
		wantFile(t, listPath(dir), listOf(t, webPatchName), "the list")
	})

	t.Run("the file is there with other content", func(t *testing.T) {
		t.Parallel()
		// For example the patch of an earlier run for another class. A
		// run changes no file that is there.
		other := strings.Replace(webPatch, "runtimeClassName: gvisor", "runtimeClassName: kata", 1)
		dir := writeManifests(t, map[string]string{webPatchName: other, "kustomization.yaml": listOf(t, webPatchName)})
		before := snapshot(t, dir)
		res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
		web := changeOf(t, res, "web")
		if web.Status != schema.PatchStatusNotEdited || web.PatchFile != "" || !strings.Contains(web.Reason, "is there with other content, and a run changes no file that is there") {
			t.Errorf("web = %+v", web)
		}
		if len(res.Spec.Files) != 0 || PatchExitCode(res) != 1 {
			t.Errorf("files = %+v, exit code = %d; want no file and 1", res.Spec.Files, PatchExitCode(res))
		}
		wantSame(t, snapshot(t, dir), before, "the component")
	})

	t.Run("the name is a directory", func(t *testing.T) {
		t.Parallel()
		dir := writeManifests(t, map[string]string{webPatchName + "/x": "x\n", "kustomization.yaml": listOf(t, "pod_other.yaml")})
		res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
		if web := changeOf(t, res, "web"); web.Status != schema.PatchStatusNotEdited || !strings.Contains(web.Reason, "is there and is not a regular file") {
			t.Errorf("web = %+v", web)
		}
		wantFile(t, listPath(dir), listOf(t, "pod_other.yaml"), "the list")
	})
}

// TestPatchKustomize_StandardInput: with a component directory no input is
