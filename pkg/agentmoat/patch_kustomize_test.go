// TestPatchKustomize_NoPatchForAnObjectWithNoName: Kustomize finds the
// target of a patch by name. An object with generateName only gets no file,
// and the exit code says that the run is partial.
func TestPatchKustomize_NoPatchForAnObjectWithNoName(t *testing.T) {
	t.Parallel()
	const job = "apiVersion: batch/v1\nkind: Job\nmetadata: {generateName: run-, namespace: agents}\nspec:\n  template:\n    spec:\n      restartPolicy: Never\n      containers:\n        - {name: c, image: example.test/c:1}\n"
	root := writeManifests(t, map[string]string{"web.yaml": plainDeployment, "job.yaml": job})
	dir := filepath.Join(t.TempDir(), "gvisor")
	res, stderr := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})

	run := changeOf(t, res, "run-")
	if run.Status != schema.PatchStatusNotEdited || run.PatchFile != "" || !strings.Contains(run.Reason, "generateName and no metadata.name") {
		t.Errorf("the change of the job = %+v", run)
	}
	if changeOf(t, res, "web").Status != schema.PatchStatusPatched {
		t.Errorf("web = %+v", changeOf(t, res, "web"))
	}
	wantEntries(t, dir, 2)
	if PatchExitCode(res) != 3 {
		t.Errorf("exit code = %d, want 3 (partial)", PatchExitCode(res))
	}
	if !strings.Contains(stderr, "1 selected workload(s) got no patch file") {
		t.Errorf("stderr:\n%s", stderr)
	}

	// Only that object: nothing is written, also no empty list.
	only := writeManifests(t, map[string]string{"job.yaml": job})
	empty := filepath.Join(t.TempDir(), "gvisor")
	res, _ = patchFiles(t, PatchOptions{ManifestPaths: []string{only}, KustomizeDir: empty, DryRun: false})
	if _, err := os.Stat(empty); !os.IsNotExist(err) || len(res.Spec.Files) != 0 || PatchExitCode(res) != 1 {
		t.Errorf("a run with no patch: stat = %v, files = %+v, exit code = %d", err, res.Spec.Files, PatchExitCode(res))
	}
}

