// TestPatchKustomize_AFileThatCannotBeWritten: a patch file that cannot be
// written is a failed workload, and the list does not name it.
func TestPatchKustomize_AFileThatCannotBeWritten(t *testing.T) {
	t.Parallel()
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs a directory that the user cannot write to")
	}
	root := patchTree(t)
	dir := writeManifests(t, map[string]string{".gitkeep": ""})
	if err := os.Chmod(dir, 0o500); err != nil { // #nosec G302 -- the test needs a directory that cannot be written.
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(dir, 0o700) }) // #nosec G302 -- so that the test directory can be removed.

	res, stderr := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
	web := changeOf(t, res, "web")
	if web.Status != schema.PatchStatusFailed || web.PatchFile != "" || !strings.Contains(web.Reason, "the patch file was not written") {
		t.Errorf("web = %+v", web)
	}
	// The list is not in the result: it would name a file that is not
	// there.
	if len(res.Spec.Files) != 1 || res.Spec.Files[0].Written || res.Spec.Files[0].Error == "" {
		t.Errorf("files = %+v; want the patch file with its error", res.Spec.Files)
	}
	wantEntries(t, dir, 1)
	if PatchExitCode(res) != 1 || !strings.Contains(stderr, "1 selected workload(s) have a patch that could not be written") {
		t.Errorf("exit code = %d, stderr:\n%s", PatchExitCode(res), stderr)
	}
}

// TestPatchKustomize_AListThatChanged: the list is written last, and only
// when it still has the bytes that were read. When it does not, the patch
// file is there and no list names it, so the workload is failed: a build
// does not use the patch. The next run finds the file and adds the entry.
func TestPatchKustomize_AListThatChanged(t *testing.T) {
	t.Parallel()
	dir := writeManifests(t, map[string]string{"kustomization.yaml": listOf(t, "pod_other.yaml"), "pod_other.yaml": "x\n"})
	list := filepath.Join(dir, "kustomization.yaml")

	run := &patchRun{
		opts:    PatchOptions{KustomizeDir: dir},
		class:   "gvisor",
		changes: []schema.PatchChange{{Target: schema.WorkloadRef{Kind: "Deployment", Namespace: "agents", Name: "web"}}},
		objects: []scanner.ManifestObject{{APIVersion: "apps/v1", Kind: "Deployment", Name: "web", Namespace: "agents", PodSpecPath: []string{"spec", "template", "spec"}}},
	}
	var err error
	if run.kustomize, err = readKustomizeDir(dir); err != nil {
		t.Fatal(err)
	}
	run.planComponent()
	// Another writer changes the list between the read and the write.
	theirs := listOf(t, "pod_other.yaml", "pod_theirs.yaml")
	if err := os.WriteFile(list, []byte(theirs), 0o600); err != nil {
		t.Fatal(err)
	}
	run.writeComponent()

	change := run.changes[0]
	if change.Status != schema.PatchStatusFailed || !strings.Contains(change.Reason, "the list of the component was not written") || !strings.Contains(change.Reason, "changed after it was read") {
		t.Errorf("change = %+v", change)
	}
	wantFile(t, list, theirs, "the list of the other writer")
	wantFile(t, filepath.Join(dir, webPatchName), webPatch, "the patch file")
	files := run.kustomize.patchFiles()
	if len(files) != 2 || !files[0].Written || files[1].Written || files[1].Error == "" {
		t.Errorf("files = %+v; want the patch file written and the list with its error", files)
	}
	wantEntries(t, dir, 3)

	// The next run: the file is there, and the entry is added.
	root := writeManifests(t, map[string]string{"web.yaml": plainDeployment})
	res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
	if res.Spec.Summary.Patched != 1 || len(res.Spec.Files) != 1 {
		t.Errorf("the next run: %+v, files %+v", res.Spec.Summary, res.Spec.Files)
	}
	wantFile(t, list, theirs+"- path: "+webPatchName+"\n", "the list after the next run")
}
