// TestPatchKustomize_ANameIsNotAPath: a name is text from a manifest, and it
// becomes a part of a file name. Whatever the name is, the file is in the
// component directory.
func TestPatchKustomize_ANameIsNotAPath(t *testing.T) {
	t.Parallel()
	const pod = "apiVersion: v1\nkind: Pod\nmetadata:\n  name: \"../../../escape\"\n  namespace: \"/abs\"\nspec:\n  containers:\n    - {name: c, image: example.test/c:1}\n"
	root := writeManifests(t, map[string]string{"pod.yaml": pod})
	outer := t.TempDir()
	dir := filepath.Join(outer, "a", "b", "gvisor")
	res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})

	if len(res.Spec.Changes) != 1 || res.Spec.Changes[0].Status != schema.PatchStatusPatched {
		t.Fatalf("changes = %+v", res.Spec.Changes)
	}
	file := res.Spec.Changes[0].PatchFile
	if filepath.Dir(file) != dir {
		t.Errorf("the patch file %s is not in %s", file, dir)
	}
	wantEntries(t, dir, 2)
	// Nothing was made next to the directory, or above it.
	wantEntries(t, filepath.Join(outer, "a", "b"), 1)
	wantEntries(t, filepath.Join(outer, "a"), 1)
	wantEntries(t, outer, 1)
	if got := readFile(t, file); !strings.Contains(got, "  name: ../../../escape\n  namespace: /abs\n") {
		t.Errorf("the patch does not name the object as the file writes it:\n%s", got)
	}
}

// TestPatchKustomize_RefusesADirectoryOfAPerson: a run writes a
// kustomization.yaml, and that changes what a directory is. So the directory
// must be new, empty, or the directory of an earlier run. In each other
// case the run stops with an error, and nothing is written.
func TestPatchKustomize_RefusesADirectoryOfAPerson(t *testing.T) {
	t.Parallel()
	ours := listOf(t, webPatchName)
	cases := map[string]struct {
		files map[string]string
		want  string
	}{
		"a kustomization of a person": {
			map[string]string{"kustomization.yaml": "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - ../base\n"},
			"does not start with the line",
		},
		"a kustomization with the other name": {map[string]string{"kustomization.yml": "resources: []\n"}, "it is the directory of another kustomization"},
		"a Kustomization file":                {map[string]string{"Kustomization": "resources: []\n"}, "it is the directory of another kustomization"},
		"manifests and no list":               {map[string]string{"deploy.yaml": plainDeployment}, "has files, and no kustomization.yaml that agentmoat wrote"},
		"our list with a field added":         {map[string]string{"kustomization.yaml": ours + "namePrefix: x-\n"}, "more than the list of patches"},
		"our list with a comment in it":       {map[string]string{"kustomization.yaml": strings.Replace(ours, "patches:\n", "patches:\n# keep\n", 1)}, "not in the layout that agentmoat writes"},
	}
	for name, tc := range cases {
		name, tc := name, tc
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			root := patchTree(t)
			dir := writeManifests(t, tc.files)
			before := snapshot(t, dir)
			for _, dryRun := range []bool{true, false} {
				_, err := Patch(t.Context(), PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: dryRun, Stderr: &strings.Builder{}})
				if err == nil || !strings.Contains(err.Error(), tc.want) || !strings.HasPrefix(err.Error(), "patch: ") {
					t.Errorf("dry-run %v: err = %v; want an error with %q", dryRun, err, tc.want)
				}
			}
			wantSame(t, snapshot(t, dir), before, "the directory after the refusal")
		})
	}
}

// TestPatchKustomize_TheDirectoryIsNotADirectory covers the paths that are
// not a directory: a file, and a list that is a symbolic link.
func TestPatchKustomize_TheDirectoryIsNotADirectory(t *testing.T) {
	t.Parallel()
	root := patchTree(t)
	file := filepath.Join(t.TempDir(), "gvisor")
	if err := os.WriteFile(file, []byte("x\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	_, err := Patch(t.Context(), PatchOptions{ManifestPaths: []string{root}, KustomizeDir: file, DryRun: false, Stderr: &strings.Builder{}})
	if err == nil || !strings.Contains(err.Error(), "is a file and not a directory") {
		t.Errorf("a file: err = %v", err)
	}

	if runtime.GOOS == "windows" {
		return
	}
	// A list that is a link: a write through it could land in another
	// directory, so it is not a list that a run adds to.
	dir, elsewhere := t.TempDir(), filepath.Join(t.TempDir(), "real.yaml")
	if err := os.WriteFile(elsewhere, []byte(listOf(t, "pod_x.yaml")), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(elsewhere, filepath.Join(dir, "kustomization.yaml")); err != nil {
		t.Fatal(err)
	}
	_, err = Patch(t.Context(), PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false, Stderr: &strings.Builder{}})
	if err == nil || !strings.Contains(err.Error(), "is not a regular file") {
		t.Errorf("a list that is a link: err = %v", err)
	}
	wantFile(t, elsewhere, listOf(t, "pod_x.yaml"), "the file behind the link")
}

