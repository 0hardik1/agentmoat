// listOf is the list of a first run with these entries.
func listOf(t *testing.T, names ...string) string {
	t.Helper()
	text, _, err := patcher.ComponentAdd(nil, names)
	if err != nil {
		t.Fatalf("ComponentAdd: %v", err)
	}
	return string(text)
}

// labeled is a compatible Deployment with a label, for runs that select a
// part of the input.
func labeled(name, tier string) string {
	return "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: " + name + "\n  labels: {tier: " + tier + "}\n" +
		"spec:\n  template:\n    spec:\n      containers:\n        - {name: c, image: example.test/c:1}\n"
}

// snapshot returns the content of each file under root, by its path from
// root. A test uses two of them to prove that nothing changed.
func snapshot(t *testing.T, root string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(rel)] = readFile(t, path)
		return nil
	})
	if err != nil {
		t.Fatalf("walk %s: %v", root, err)
	}
	return files
}

// wantSame checks that two snapshots are equal.
func wantSame(t *testing.T, got, want map[string]string, what string) {
	t.Helper()
	if len(got) != len(want) {
		t.Errorf("%s: %d files, want %d", what, len(got), len(want))
	}
	for name, text := range want {
		if got[name] != text {
			t.Errorf("%s: %s is\n%s\nwant\n%s", what, name, got[name], text)
		}
	}
}

// wantDryRunFiles checks the files of a dry-run result for the web workload:
// the patch file and then the list, each one new and not written.
func wantDryRunFiles(t *testing.T, res *schema.PatchResult, dir string) {
	t.Helper()
	if len(res.Spec.Files) != 2 {
		t.Fatalf("%d files, want 2: %+v", len(res.Spec.Files), res.Spec.Files)
	}
	for _, f := range res.Spec.Files {
		if !f.Created || f.Written || f.Removed != 0 || !strings.HasPrefix(f.Diff, "--- /dev/null\n") {
			t.Errorf("the file %s = %+v; want a new file that is not written", f.Path, f)
		}
	}
	if got := res.Spec.Files[0]; got.Path != filepath.Join(dir, webPatchName) || got.Added != strings.Count(webPatch, "\n") {
		t.Errorf("the patch file = %+v", got)
	}
	if got := res.Spec.Files[1].Path; got != filepath.Join(dir, "kustomization.yaml") {
		t.Errorf("the second file = %s, want the list", got)
	}
}

func TestPatchKustomize_DryRunWritesNothing(t *testing.T) {
	t.Parallel()
	root := patchTree(t)
	before := snapshot(t, root)
	dir := filepath.Join(t.TempDir(), "overlay", "gvisor")
	res, stderr := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: true})

	if got, want := res.Spec.Summary, (schema.PatchSummary{Total: 6, Selected: 1, Patched: 1, Excluded: 5, Files: 2}); got != want {
		t.Errorf("summary = %+v, want %+v", got, want)
	}
	if res.Metadata.KustomizeDir != dir || !res.Metadata.DryRun {
		t.Errorf("metadata = %+v", res.Metadata)
	}
	web := changeOf(t, res, "web")
	if web.Status != schema.PatchStatusPatched || web.PatchFile != filepath.Join(dir, webPatchName) || web.Line != 0 {
		t.Errorf("the change of web = %+v", web)
	}
	if web.Origin == nil || !strings.HasSuffix(web.Origin.File, "web.yaml") {
		t.Errorf("the change keeps the place of the source object: %+v", web.Origin)
	}
	wantDryRunFiles(t, res, dir)
	if _, err := os.Stat(filepath.Dir(dir)); !os.IsNotExist(err) {
		t.Errorf("a dry-run made a directory: %v", err)
	}
	wantSame(t, snapshot(t, root), before, "the source files after a dry-run")
	for _, want := range []string{"dry-run: 2 file(s) would be written in " + dir, "no source file changes", "add the directory " + dir + " to `components:`"} {
		if !strings.Contains(stderr, want) {
			t.Errorf("stderr lacks %q:\n%s", want, stderr)
		}
	}
	if PatchExitCode(res) != 0 {
		t.Errorf("exit code = %d, want 0", PatchExitCode(res))
	}
}

func TestPatchKustomize_WritesTheComponent(t *testing.T) {
	t.Parallel()
	root := patchTree(t)
	before := snapshot(t, root)
	dir := filepath.Join(t.TempDir(), "overlay", "gvisor")
	res, stderr := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})

	wantSame(t, snapshot(t, dir), map[string]string{
		webPatchName:         webPatch,
		"kustomization.yaml": listOf(t, webPatchName),
	}, "the component")
	wantEntries(t, dir, 2)
	wantMode(t, filepath.Join(dir, webPatchName), 0o644)
	wantMode(t, filepath.Join(dir, "kustomization.yaml"), 0o644)
	// The one thing that this form promises about the input: it is not
	// changed.
	wantSame(t, snapshot(t, root), before, "the source files after a run")

	for _, f := range res.Spec.Files {
		if !f.Created || !f.Written || f.Error != "" {
			t.Errorf("the file %s = %+v; want a new file that is written", f.Path, f)
		}
	}
	if !strings.Contains(stderr, "2 of 2 file(s) written in "+dir+"; no source file changed") {
		t.Errorf("stderr:\n%s", stderr)
	}
	if PatchExitCode(res) != 0 {
		t.Errorf("exit code = %d, want 0", PatchExitCode(res))
	}
}

// TestPatchKustomize_ASecondRunChangesNothing: the source files never get
// the class in this form, so a run must find its own patches again.
func TestPatchKustomize_ASecondRunChangesNothing(t *testing.T) {
	t.Parallel()
	root := patchTree(t)
	dir := filepath.Join(t.TempDir(), "gvisor")
	patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
	before := snapshot(t, dir)

	for _, dryRun := range []bool{true, false} {
		res, stderr := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: dryRun})
		if got, want := res.Spec.Summary, (schema.PatchSummary{Total: 6, Excluded: 6}); got != want {
			t.Errorf("dry-run %v: summary = %+v, want %+v", dryRun, got, want)
		}
		if len(res.Spec.Files) != 0 || len(res.Spec.Changes) != 0 {
			t.Errorf("dry-run %v: files = %+v, changes = %+v; want none", dryRun, res.Spec.Files, res.Spec.Changes)
		}
		if got, want := excludedReasons(res)["web"], "the component has the patch for it already ("+filepath.Join(dir, webPatchName)+")"; got != want {
			t.Errorf("dry-run %v: reason = %q, want %q", dryRun, got, want)
		}
		if !strings.Contains(stderr, "nothing to change: the component "+dir+" has the patch for each of the 1 workload(s) that can move") {
			t.Errorf("dry-run %v: stderr:\n%s", dryRun, stderr)
		}
		if PatchExitCode(res) != 0 {
			t.Errorf("dry-run %v: exit code = %d, want 0", dryRun, PatchExitCode(res))
		}
	}
	wantSame(t, snapshot(t, dir), before, "the component after the second run")
	wantEntries(t, dir, 2)
}

// TestPatchKustomize_ARunOnlyAdds: a later run for more workloads puts its
// entries at the end of the list. The files and the lines that are there
// stay as they are, so the diff of the run has added lines only.
func TestPatchKustomize_ARunOnlyAdds(t *testing.T) {
	t.Parallel()
	root := writeManifests(t, map[string]string{"b.yaml": labeled("b", "one"), "a.yaml": labeled("a", "two"), "c.yaml": labeled("c", "two")})
	dir := filepath.Join(t.TempDir(), "gvisor")
	list := filepath.Join(dir, "kustomization.yaml")

	patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, LabelSelector: "tier=one", DryRun: false})
	first := readFile(t, list)
	if first != listOf(t, "deployment.apps_b.yaml") {
		t.Fatalf("the list of the first run:\n%s", first)
	}
	// A person changes the comment. A later run keeps the change.
	first = strings.Replace(first, patcher.KustomizeMarker+"\n", patcher.KustomizeMarker+"\n# Owner: the platform team.\n", 1)
	if err := os.WriteFile(list, []byte(first), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(list, 0o600); err != nil {
		t.Fatal(err)
	}

	res, _ := patchFiles(t, PatchOptions{ManifestPaths: []string{root}, KustomizeDir: dir, DryRun: false})
	if got, want := res.Spec.Summary, (schema.PatchSummary{Total: 3, Selected: 2, Patched: 2, Excluded: 1, Files: 3}); got != want {
		t.Errorf("summary = %+v, want %+v", got, want)
	}
	wantFile(t, list, first+"- path: deployment.apps_a.yaml\n- path: deployment.apps_c.yaml\n", "the list after the second run")
	wantMode(t, list, 0o600) // a file that is there keeps its mode
	wantEntries(t, dir, 4)
	for _, f := range res.Spec.Files {
		isList := f.Path == list
		if f.Created == isList || f.Removed != 0 || !f.Written {
			t.Errorf("the file %s = %+v; want new patch files, and a list with added lines only", f.Path, f)
		}
		if isList && (f.Added != 2 || !strings.Contains(f.Diff, "\n - path: deployment.apps_b.yaml\n+- path: deployment.apps_a.yaml\n+- path: deployment.apps_c.yaml\n")) {
			t.Errorf("the diff of the list:\n%s", f.Diff)
		}
	}
}

