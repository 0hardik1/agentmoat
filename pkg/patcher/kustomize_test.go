// writtenOf returns how a text writes each of its workloads, in the order of
// the scanner.
func writtenOf(t *testing.T, text string) []scanner.ManifestObject {
	t.Helper()
	found, err := scanner.FromManifests([]scanner.ManifestInput{{Name: "test.yaml", Data: []byte(text)}}, scanner.ManifestOptions{})
	if err != nil {
		t.Fatalf("FromManifests: %v", err)
	}
	return found.Written
}

// patchHeader is the comment at the top of each patch file.
const patchHeader = "# Generated by `agentmoat patch --kustomize`.\n" +
	"# A strategic merge patch: it puts one workload in the RuntimeClass.\n" +
	"# To take the workload out again, remove this file and its line in kustomization.yaml.\n"

func TestKustomizePatch_EachKind(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name     string
		text     string
		wantFile string
		want     string
	}{
		{
			name:     "a Deployment with a namespace",
			text:     "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: web\n  namespace: shop\nspec:\n  template:\n    spec:\n      containers:\n        - {name: c, image: busybox}\n",
			wantFile: "deployment.apps_shop_web.yaml",
			want:     "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: web\n  namespace: shop\nspec:\n  template:\n    spec:\n      runtimeClassName: gvisor\n",
		},
		{
			name:     "a Pod with no namespace: the patch has none",
			text:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: once\nspec:\n  containers:\n    - {name: c, image: busybox}\n",
			wantFile: "pod_once.yaml",
			want:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: once\nspec:\n  runtimeClassName: gvisor\n",
		},
		{
			name:     "a CronJob",
			text:     "apiVersion: batch/v1\nkind: CronJob\nmetadata:\n  name: nightly\nspec:\n  schedule: \"0 0 * * *\"\n  jobTemplate:\n    spec:\n      template:\n        spec:\n          restartPolicy: Never\n          containers:\n            - {name: c, image: busybox}\n",
			wantFile: "cronjob.batch_nightly.yaml",
			want:     "apiVersion: batch/v1\nkind: CronJob\nmetadata:\n  name: nightly\nspec:\n  jobTemplate:\n    spec:\n      template:\n        spec:\n          runtimeClassName: gvisor\n",
		},
		{
			// The scanner calls this kind "Rollout.argoproj.io". The patch
			// must have the kind and the apiVersion of the file.
			name:     "a kind that is not one of the six",
			text:     "apiVersion: argoproj.io/v1alpha1\nkind: Rollout\nmetadata:\n  name: canary\nspec:\n  template:\n    spec:\n      containers:\n        - {name: c, image: busybox}\n",
			wantFile: "rollout.argoproj.io_canary.yaml",
			want:     "apiVersion: argoproj.io/v1alpha1\nkind: Rollout\nmetadata:\n  name: canary\nspec:\n  template:\n    spec:\n      runtimeClassName: gvisor\n",
		},
		{
			// An old chart: the patch has the apiVersion of the file, and
			// not the one that the kind has today.
			name:     "an old apiVersion",
			text:     "apiVersion: extensions/v1beta1\nkind: Deployment\nmetadata:\n  name: old\nspec:\n  template:\n    spec:\n      containers:\n        - {name: c, image: busybox}\n",
			wantFile: "deployment.extensions_old.yaml",
			want:     "apiVersion: extensions/v1beta1\nkind: Deployment\nmetadata:\n  name: old\nspec:\n  template:\n    spec:\n      runtimeClassName: gvisor\n",
		},
		{
			// The text edit refuses the next three forms. A patch file only
			// needs to read them.
			name:     "flow style",
			text:     "apiVersion: v1\nkind: Pod\nmetadata: {name: flow, namespace: shop}\nspec: {containers: [{name: c, image: busybox}]}\n",
			wantFile: "pod_shop_flow.yaml",
			want:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: flow\n  namespace: shop\nspec:\n  runtimeClassName: gvisor\n",
		},
		{
			name:     "JSON",
			text:     `{"apiVersion": "v1", "kind": "Pod", "metadata": {"name": "json"}, "spec": {"containers": [{"name": "c", "image": "busybox"}]}}` + "\n",
			wantFile: "pod_json.yaml",
			want:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: json\nspec:\n  runtimeClassName: gvisor\n",
		},
		{
			name:     "an anchor on the pod spec",
			text:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: anchored\nspec: &shared\n  containers:\n    - {name: c, image: busybox}\n",
			wantFile: "pod_anchored.yaml",
			want:     "apiVersion: v1\nkind: Pod\nmetadata:\n  name: anchored\nspec:\n  runtimeClassName: gvisor\n",
		},
	}
	for _, tc := range cases {
		written := writtenOf(t, tc.text)
		if len(written) != 1 {
			t.Errorf("%s: %d workloads, want 1", tc.name, len(written))
			continue
		}
		file, patch, reason := KustomizePatch(written[0], "gvisor")
		if reason != "" {
			t.Errorf("%s: no patch: %s", tc.name, reason)
			continue
		}
		if file != tc.wantFile {
			t.Errorf("%s: file name = %q, want %q", tc.name, file, tc.wantFile)
		}
		if string(patch) != patchHeader+tc.want {
			t.Errorf("%s: patch =\n%s\nwant\n%s", tc.name, patch, patchHeader+tc.want)
		}
	}
}

// TestKustomizePatch_ManyObjects: each object of a file gets its own patch,
// also an item of a List, and each patch names its own object.
func TestKustomizePatch_ManyObjects(t *testing.T) {
	t.Parallel()
	text := manyPods(3, 0) + "---\napiVersion: v1\nkind: List\nitems:\n  - apiVersion: v1\n    kind: Pod\n    metadata: {name: in-list}\n    spec:\n      containers:\n        - {name: c, image: busybox}\n"
	files := map[string]bool{}
	var names []string
	for _, obj := range writtenOf(t, text) {
		file, patch, reason := KustomizePatch(obj, "gvisor")
		if reason != "" {
			t.Fatalf("%s: no patch: %s", obj.Name, reason)
		}
		if !strings.Contains(string(patch), "\n  name: "+obj.Name+"\n") {
			t.Errorf("the patch for %s does not name it:\n%s", obj.Name, patch)
		}
		if files[file] {
			t.Errorf("the file name %s is there two times", file)
		}
		files[file] = true
		names = append(names, obj.Name)
	}
	if len(names) != 4 || !files["pod_in-list.yaml"] {
		t.Errorf("patches for %v, files %v; want 4 with the item of the List", names, files)
	}
}

