// TestKustomizePatch_TextFromAManifestIsData: a name, a namespace, a kind, or
// an apiVersion with YAML in it is a value in the patch, and never structure.
// A class name that YAML reads as another type is a string too.
func TestKustomizePatch_TextFromAManifestIsData(t *testing.T) {
	t.Parallel()
	const hostile = "x\nspec:\n  hostNetwork: true\n# "
	for name, obj := range map[string]scanner.ManifestObject{
		"name":       {APIVersion: "v1", Kind: "Pod", Name: hostile, PodSpecPath: []string{"spec"}},
		"namespace":  {APIVersion: "v1", Kind: "Pod", Name: "p", Namespace: hostile, PodSpecPath: []string{"spec"}},
		"kind":       {APIVersion: "v1", Kind: hostile, Name: "p", PodSpecPath: []string{"spec"}},
		"apiVersion": {APIVersion: hostile, Kind: "Pod", Name: "p", PodSpecPath: []string{"spec"}},
		"yaml types": {APIVersion: "1.0", Kind: "true", Name: "null", Namespace: "0x10", PodSpecPath: []string{"spec"}},
	} {
		file, patch, reason := KustomizePatch(obj, "on")
		if reason != "" {
			t.Errorf("%s: no patch: %s", name, reason)
			continue
		}
		if file != filepath.Base(file) || strings.ContainsAny(file, "/\\\n") {
			t.Errorf("%s: the file name %q is not a plain name", name, file)
		}
		var got struct {
			APIVersion string `json:"apiVersion"`
			Kind       string `json:"kind"`
			Metadata   struct {
				Name      string `json:"name"`
				Namespace string `json:"namespace"`
			} `json:"metadata"`
			Spec map[string]any `json:"spec"`
		}
		if err := yaml.UnmarshalStrict(patch, &got); err != nil {
			t.Errorf("%s: the patch does not decode: %v\n%s", name, err, patch)
			continue
		}
		if got.APIVersion != obj.APIVersion || got.Kind != obj.Kind || got.Metadata.Name != obj.Name || got.Metadata.Namespace != obj.Namespace {
			t.Errorf("%s: the patch names %+v, want the fields of %+v", name, got, obj)
		}
		if len(got.Spec) != 1 || got.Spec["runtimeClassName"] != "on" {
			t.Errorf("%s: spec = %v, want only runtimeClassName \"on\" (a string)", name, got.Spec)
		}
	}
}

// TestKustomizeFileName: a file name is made from text of a manifest. It has
// no path separator, two objects never share one, and the same object gets
// the same name each time.
func TestKustomizeFileName(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		obj  scanner.ManifestObject
		want string
	}{
		{scanner.ManifestObject{APIVersion: "apps/v1", Kind: "Deployment", Name: "web"}, "deployment.apps_web.yaml"},
		{scanner.ManifestObject{APIVersion: "apps/v1", Kind: "Deployment", Name: "web", Namespace: "shop"}, "deployment.apps_shop_web.yaml"},
		{scanner.ManifestObject{APIVersion: "v1", Kind: "Pod", Name: "a.b-c"}, "pod_a.b-c.yaml"},
	} {
		if got := KustomizeFileName(tc.obj); got != tc.want {
			t.Errorf("KustomizeFileName(%+v) = %q, want %q", tc.obj, got, tc.want)
		}
	}

	// The join is not ambiguous: a namespace and a name cannot have "_".
	a := KustomizeFileName(scanner.ManifestObject{APIVersion: "v1", Kind: "Pod", Namespace: "a", Name: "b-c"})
	b := KustomizeFileName(scanner.ManifestObject{APIVersion: "v1", Kind: "Pod", Name: "a-b-c"})
	if a == b {
		t.Errorf("two objects share the file name %q", a)
	}

	hostile := []scanner.ManifestObject{
		{APIVersion: "v1", Kind: "Pod", Name: "../../etc/passwd"},
		{APIVersion: "v1", Kind: "Pod", Name: ".."},
		{APIVersion: "v1", Kind: "..", Name: ".."},
		{APIVersion: "v1", Kind: ".hidden", Name: "p"},
		{APIVersion: "v1", Kind: "Pod", Name: "a/b"},
		{APIVersion: "v1", Kind: "Pod", Name: "a_b"},
		{APIVersion: "v1", Kind: "Pod", Name: "a\nb"},
		{APIVersion: "v1", Kind: "Pod", Name: "A-B"},
		{APIVersion: "v1", Kind: "Pod", Name: strings.Repeat("x", 300)},
		{APIVersion: "v1", Kind: "Pod", Name: strings.Repeat("x", 299) + "y"},
		{APIVersion: "../v1", Kind: "Po/d", Name: "p", Namespace: "n\\s"},
	}
	seen := map[string]bool{}
	for _, obj := range hostile {
		name := KustomizeFileName(obj)
		if name != filepath.Base(name) || strings.ContainsAny(name, "/\\\n") || strings.HasPrefix(name, ".") || len(name) > 140 || name != strings.ToLower(name) {
			t.Errorf("KustomizeFileName(%+v) = %q: not a plain file name in lower case", obj, name)
		}
		if !regexp.MustCompile(`_[0-9a-f]{8}\.yaml$`).MatchString(name) {
			t.Errorf("KustomizeFileName(%+v) = %q: a changed name must end with the hash", obj, name)
		}
		if seen[name] {
			t.Errorf("the file name %q is there two times", name)
		}
		seen[name] = true
		if again := KustomizeFileName(obj); again != name {
			t.Errorf("the name is not stable: %q then %q", name, again)
		}
	}
	// A name that was changed has a hash, so it cannot be the name of
	// another object that is valid: "a/b" and "a-b" are two files.
	changed := KustomizeFileName(scanner.ManifestObject{APIVersion: "v1", Kind: "Pod", Name: "a/b"})
	valid := KustomizeFileName(scanner.ManifestObject{APIVersion: "v1", Kind: "Pod", Name: "a-b"})
	if changed == valid {
		t.Errorf("a changed name and a valid name share the file %q", valid)
	}
}

// newList is the list of a first run.
func newList(t *testing.T, paths ...string) []byte {
	t.Helper()
	text, _, err := ComponentAdd(nil, paths)
	if err != nil {
		t.Fatalf("ComponentAdd: %v", err)
	}
	return text
}

func TestComponentAdd_ANewList(t *testing.T) {
	t.Parallel()
	text, added, err := ComponentAdd(nil, []string{"pod_b.yaml", "deployment.apps_web.yaml", "pod_b.yaml"})
	if err != nil {
		t.Fatalf("ComponentAdd: %v", err)
	}
	if !strings.HasPrefix(string(text), KustomizeMarker+"\n") {
		t.Errorf("the file does not start with the marker:\n%s", text)
	}
	const body = "apiVersion: kustomize.config.k8s.io/v1alpha1\nkind: Component\npatches:\n- path: deployment.apps_web.yaml\n- path: pod_b.yaml\n"
	if !strings.HasSuffix(string(text), "\n"+body) {
		t.Errorf("the file is\n%s\nwant it to end with\n%s", text, body)
	}
	if got := strings.Join(added, ","); got != "deployment.apps_web.yaml,pod_b.yaml" {
		t.Errorf("added = %s", got)
	}
	paths, err := ComponentPaths(text)
	if err != nil || strings.Join(paths, ",") != "deployment.apps_web.yaml,pod_b.yaml" {
		t.Errorf("ComponentPaths = %v, %v", paths, err)
	}
}

// TestComponentAdd_AddsAtTheEnd: a later run adds lines and changes nothing
// that is there, also after a person removed an entry, changed the order, or
// changed the comment.
func TestComponentAdd_AddsAtTheEnd(t *testing.T) {
	t.Parallel()
	first := string(newList(t, "pod_a.yaml", "pod_c.yaml", "pod_e.yaml"))
	edited := strings.Replace(first, KustomizeMarker+"\n", KustomizeMarker+"\n# The platform team owns this directory.\n", 1)
	edited = strings.Replace(edited, "- path: pod_a.yaml\n- path: pod_c.yaml\n- path: pod_e.yaml\n", "- path: pod_e.yaml\n- path: pod_a.yaml\n", 1)

	for name, tc := range map[string]struct {
		old       string
		add       []string
		wantAdded string
	}{
		"new paths":          {first, []string{"pod_d.yaml", "pod_b.yaml"}, "- path: pod_b.yaml\n- path: pod_d.yaml\n"},
		"a path that is in":  {first, []string{"pod_c.yaml", "pod_z.yaml"}, "- path: pod_z.yaml\n"},
		"an edited old list": {edited, []string{"pod_c.yaml", "pod_a.yaml", "pod_b.yaml"}, "- path: pod_b.yaml\n- path: pod_c.yaml\n"},
	} {
		text, added, err := ComponentAdd([]byte(tc.old), tc.add)
		if err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		if string(text) != tc.old+tc.wantAdded {
			t.Errorf("%s: the list is\n%s\nwant the old text and then\n%s", name, text, tc.wantAdded)
		}
		if got := strings.Count(tc.wantAdded, "\n"); len(added) != got {
			t.Errorf("%s: added = %v, want %d paths", name, added, got)
		}
	}

	// Nothing to add: the same bytes come back.
	text, added, err := ComponentAdd([]byte(edited), []string{"pod_a.yaml"})
	if err != nil || string(text) != edited || len(added) != 0 {
		t.Errorf("nothing to add: text changed = %v, added = %v, err = %v", string(text) != edited, added, err)
	}

	// An old list with no entry: the one case with a changed line.
	empty := strings.Replace(first, "patches:\n- path: pod_a.yaml\n- path: pod_c.yaml\n- path: pod_e.yaml\n", "patches: []\n", 1)
	text, _, err = ComponentAdd([]byte(empty), []string{"pod_a.yaml"})
	if want := strings.Replace(empty, "patches: []\n", "patches:\n- path: pod_a.yaml\n", 1); err != nil || string(text) != want {
		t.Errorf("an empty old list: %v\n%s", err, text)
	}
}

// TestComponentAdd_RefusesAFileOfAPerson: a run writes the list again from
// its entries. A file that has more in it would lose that, and a file with
// no marker was never a file of a run, so the two are refused.
func TestComponentAdd_RefusesAFileOfAPerson(t *testing.T) {
	t.Parallel()
	ours := string(newList(t, "pod_a.yaml", "pod_b.yaml"))
	for name, tc := range map[string]struct{ text, want string }{
		"no marker":               {strings.TrimPrefix(ours, KustomizeMarker+"\n"), "does not start with the line"},
		"the marker is not first": {"\n" + ours, "does not start with the line"},
		"an added field":          {ours + "namePrefix: x-\n", "more than the list of patches"},
		"a patch with a target":   {strings.Replace(ours, "- path: pod_a.yaml\n", "- path: pod_a.yaml\n  target: {kind: Pod}\n", 1), "more than the list of patches"},
		"a Kustomization":         {strings.Replace(strings.Replace(ours, "kind: Component", "kind: Kustomization", 1), "v1alpha1", "v1beta1", 1), "is not a Component"},
		"a patch with no path":    {strings.Replace(ours, "- path: pod_a.yaml\n", "- path: \"\"\n", 1), "a patch with no path"},
		"a comment in the list":   {strings.Replace(ours, "- path: pod_b.yaml\n", "# not this one\n- path: pod_b.yaml\n", 1), "not in the layout"},
		"a blank line":            {strings.Replace(ours, "kind: Component\n", "kind: Component\n\n", 1), "not in the layout"},
		"other quotes":            {strings.Replace(ours, "- path: pod_a.yaml\n", "- path: \"pod_a.yaml\"\n", 1), "not in the layout"},
		"not YAML":                {KustomizeMarker + "\n{{ .Values.x }}\n", "more than the list of patches"},
		"only the marker":         {KustomizeMarker + "\n", "is not a Component"},
	} {
		for _, call := range []func() error{
			func() error { _, err := ComponentPaths([]byte(tc.text)); return err },
			func() error { _, _, err := ComponentAdd([]byte(tc.text), []string{"pod_z.yaml"}); return err },
		} {
			if err := call(); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("%s: err = %v; want an error with %q", name, err, tc.want)
			}
		}
	}
}

func TestFileDiff(t *testing.T) {
	t.Parallel()
	const one = "a\nb\n"
	if got := FileDiff("dir/new.yaml", nil, []byte(one), false); got != "--- /dev/null\n+++ b/dir/new.yaml\n@@ -0,0 +1,2 @@\n+a\n+b\n" {
		t.Errorf("the diff of a new file =\n%s", got)
	}
	if got := FileDiff("dir/same.yaml", []byte(one), []byte(one), true); got != "" {
		t.Errorf("the diff of a file with no change = %q", got)
	}
	// An empty file that is there is not a new file.
	if got := FileDiff("f", nil, []byte(one), true); got != "--- a/f\n+++ b/f\n@@ -0,0 +1,2 @@\n+a\n+b\n" {
		t.Errorf("the diff from an empty file =\n%s", got)
	}

	old := "h1\nh2\nh3\nh4\nlist:\n- a\n- c\ntail\n"
	added := "h1\nh2\nh3\nh4\nlist:\n- a\n- b\n- c\ntail\n"
	if got, want := FileDiff("k.yaml", []byte(old), []byte(added), true), "--- a/k.yaml\n+++ b/k.yaml\n@@ -4,5 +4,6 @@\n h4\n list:\n - a\n+- b\n - c\n tail\n"; got != want {
		t.Errorf("the diff of one added line =\n%s\nwant\n%s", got, want)
	}
	if a, r := DiffStat(FileDiff("k.yaml", []byte(old), []byte(added), true)); a != 1 || r != 0 {
		t.Errorf("DiffStat of one added line = +%d -%d", a, r)
	}
	// A line of the file that starts with "-" or "+" is counted by its
	// marker, and the two header lines are not counted.
	if a, r := DiffStat(FileDiff("k.yaml", nil, []byte("--- x\n+++ y\n- a\n"), false)); a != 3 || r != 0 {
		t.Errorf("DiffStat of a new file with three lines = +%d -%d", a, r)
	}
	if a, r := DiffStat(""); a != 0 || r != 0 {
		t.Errorf("DiffStat of no diff = +%d -%d", a, r)
	}
	changed := "h1\nh2\nh3\nh4\nlist:\n- a\n- x\ntail"
	if got, want := FileDiff("k.yaml", []byte(old), []byte(changed), true), "--- a/k.yaml\n+++ b/k.yaml\n@@ -4,5 +4,5 @@\n h4\n list:\n - a\n-- c\n-tail\n+- x\n+tail\n\\ No newline at end of file\n"; got != want {
		t.Errorf("the diff of a changed line =\n%s\nwant\n%s", got, want)
	}
	if a, r := DiffStat(FileDiff("k.yaml", []byte(old), []byte(changed), true)); a != 2 || r != 2 {
		t.Errorf("DiffStat of two changed lines = +%d -%d", a, r)
	}
}

// TestFileDiff_GitApply: git makes the new file from the old one and the
// diff, also when the file is new.
func TestFileDiff_GitApply(t *testing.T) {
	t.Parallel()
	git, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git is not installed")
	}
	old := string(newList(t, "pod_a.yaml", "pod_c.yaml"))
	cases := map[string]struct {
		old    string
		exists bool
		text   string
	}{
		"a new file":             {"", false, string(newList(t, "pod_a.yaml"))},
		"lines added at the end": {old, true, old + "- path: pod_d.yaml\n- path: pod_e.yaml\n"},
		"a line added inside":    {old, true, strings.Replace(old, "- path: pod_c.yaml\n", "- path: pod_b.yaml\n- path: pod_c.yaml\n", 1)},
		"lines changed":          {old, true, strings.Replace(old, "pod_c.yaml", "pod_x.yaml", 1)},
		"everything is replaced": {"one\ntwo\n", true, "three\n"},
	}
	for name, tc := range cases {
		name, tc := name, tc
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			path := filepath.Join(dir, "gvisor", "file.yaml")
			if tc.exists {
				if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, []byte(tc.old), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			diff := FileDiff("gvisor/file.yaml", []byte(tc.old), []byte(tc.text), tc.exists)
			cmd := exec.Command(git, "apply", "-") // #nosec G204 -- git from PATH, fixed arguments.
			cmd.Dir = dir
			cmd.Stdin = strings.NewReader(diff)
			if out, err := cmd.CombinedOutput(); err != nil {
				t.Fatalf("git apply: %v\n%s\nthe diff:\n%s", err, out, diff)
			}
			got, err := os.ReadFile(path) // #nosec G304 -- a path under t.TempDir().
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tc.text {
				t.Errorf("git made\n%q\nwant\n%q\nthe diff:\n%s", got, tc.text, diff)
			}
		})
	}
}
