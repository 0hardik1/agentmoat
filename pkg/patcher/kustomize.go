// Package patcher: the Kustomize form of the change.
//
// AddRuntimeClass edits the source files. That is correct for plain
// manifests, and for a Kustomize base when every overlay of the base must
// move. It is not what a team wants that moves one environment first: a
// change to the base changes each overlay.
//
// For that case this file makes the change as a Kustomize component: one
// strategic merge patch for each workload, and a kustomization.yaml of kind
// Component that lists them. The kustomization that must move adds the
// directory to its `components:`, and the source files stay as they are.
//
// Unlike the text edit, these files are new and are generated, so they are
// written from data with a YAML encoder. Three rules come from how Kustomize
// finds the target of a patch. Each one was found with `kubectl kustomize`
// (Kustomize 5.8), and scripts/offline-smoke.sh builds real trees to keep
// them true:
//
//   - A patch names its target by apiVersion, kind, name, and namespace. So
//     all four are the ones of the source object as it is written
//     (scanner.ManifestObject). The names of a scan report are not the
//     text: the kind of a custom resource has the group in it
//     ("Rollout.argoproj.io"), there is no apiVersion, and the namespace can
//     be the default of the command line.
//   - The namespace must be in the patch when the object has one, and must
//     not be when the object has none. A patch with another namespace does
//     not match, and the build fails.
//   - The names are the ones that the kustomization reads from its
//     `resources:`, before its own namePrefix and namespace. So the input of
//     `patch` must be those resources (the files of the base, or the output
//     of the base), and not the output of the kustomization that will use
//     the component.
//
// The functions here are pure: values in, file names and file contents out.
// pkg/agentmoat reads and writes the directory.
package patcher

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"reflect"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/0hardik1/agentmoat/pkg/scanner"
)

// KustomizeMarker is the first line of each file that this package makes for
// a component. A kustomization.yaml without it is a file of a person, and a
// run does not write over it.
const KustomizeMarker = "# Generated by `agentmoat patch --kustomize`."

// KustomizationFile is the name of the file that lists the patches.
const KustomizationFile = "kustomization.yaml"

// The reasons why an object gets no patch file. They are text for a person:
// each one says what the form is and what to do.
const (
	reasonNoTypeOfItsOwn = "the object names no apiVersion or no kind of its own (an item of a typed list): " +
		"a Kustomize patch must name them. Write the patch by hand"
	reasonNoName = "the object has generateName and no metadata.name: a Kustomize patch finds its target by name, " +
		"so there is no patch for it"
)

// KustomizePatch returns the name and the content of the patch file for one
// object: a strategic merge patch that sets runtimeClassName on the pod spec
// and has nothing else. When there can be no patch, it returns the reason.
//
// Every form of input works here, also the ones that AddRuntimeClass does
// not edit (JSON, flow style, an anchor): the source is only read.
func KustomizePatch(obj scanner.ManifestObject, className string) (fileName string, patch []byte, reason string) {
	if err := ValidClassName(className); err != nil {
		return "", nil, err.Error()
	}
	switch {
	case obj.APIVersion == "" || obj.Kind == "":
		return "", nil, reasonNoTypeOfItsOwn
	case obj.Name == "":
		return "", nil, reasonNoName
	case len(obj.PodSpecPath) == 0:
		return "", nil, "the place of the pod spec in the object is not known: write the patch by hand"
	}
	patch, err := kustomizePatch(obj, className)
	if err != nil {
		return "", nil, "the patch for this object did not pass its own check, so it is not written: " + err.Error()
	}
	return KustomizeFileName(obj), patch, ""
}

// kustomizePatch returns the content of one patch file.
//
// The text comes from an encoder, so a name with a character that has a
// meaning in YAML is quoted and stays data. The result is decoded again and
// must be equal to what was encoded: a patch that names another object than
// the one it is for would be an error that nobody sees until a build.
func kustomizePatch(obj scanner.ManifestObject, className string) ([]byte, error) {
	metadata := map[string]any{"name": obj.Name}
	if obj.Namespace != "" {
		metadata["namespace"] = obj.Namespace
	}
	// The pod spec, with the keys of the path around it:
	// {spec: {template: {spec: {runtimeClassName: gvisor}}}}.
	var nested any = map[string]any{"runtimeClassName": className}
	for i := len(obj.PodSpecPath) - 1; i >= 0; i-- {
		nested = map[string]any{obj.PodSpecPath[i]: nested}
	}
	doc := nested.(map[string]any)
	for _, key := range []string{"apiVersion", "kind", "metadata"} {
		if _, taken := doc[key]; taken {
			return nil, fmt.Errorf("the pod spec path starts with %q", key)
		}
	}
	doc["apiVersion"], doc["kind"], doc["metadata"] = obj.APIVersion, obj.Kind, metadata

	body, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	var back map[string]any
	if err := yaml.Unmarshal(body, &back); err != nil {
		return nil, err
	}
	if !reflect.DeepEqual(back, doc) {
		return nil, fmt.Errorf("the patch text does not decode to the same object")
	}
	header := KustomizeMarker + "\n" +
		"# A strategic merge patch: it puts one workload in the RuntimeClass.\n" +
		"# To take the workload out again, remove this file and its line in " + KustomizationFile + ".\n"
	return append([]byte(header), body...), nil
}

// KustomizeFileName returns the file name of the patch for one object:
//
//	<kind>[.<group>]_[<namespace>_]<name>.yaml     deployment.apps_shop_web.yaml
//
// The parts are joined with "_", which a Kubernetes name cannot have, so two
// objects with valid names never get the same file name.
//
// A name is text from a manifest, and the scanner does not check it. So each
// character that is not a lower-case letter, a digit, "." or "-" becomes
// "-", a "." at the start of a part too, and then a short hash of the four
// fields is added. The result is always one plain file name (no path
// separator, no "..", no hidden file), it is in lower case only (two names
// cannot differ only in case, which matters on macOS), and a name that was
// changed cannot be the name of another object.
func KustomizeFileName(obj scanner.ManifestObject) string {
	kind := strings.ToLower(obj.Kind)
	if group, _, hasGroup := strings.Cut(obj.APIVersion, "/"); hasGroup {
		kind += "." + strings.ToLower(group)
	}
	parts := []string{kind}
	if obj.Namespace != "" {
		parts = append(parts, obj.Namespace)
	}
	parts = append(parts, obj.Name)

	changed := false
	for i, part := range parts {
		clean := strings.Map(func(r rune) rune {
			if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '.' || r == '-' {
				return r
			}
			return '-'
		}, part)
		if clean == "" || clean[0] == '.' {
			clean = "-" + strings.TrimPrefix(clean, ".")
		}
		if clean != part {
			changed = true
		}
		parts[i] = clean
	}
	name := strings.Join(parts, "_")
	// A file name has a limit of 255 bytes on the common file systems.
	const limit = 120
	if len(name) > limit {
		name, changed = name[:limit], true
	}
	if changed {
		sum := sha256.Sum256([]byte(obj.APIVersion + "\x00" + obj.Kind + "\x00" + obj.Namespace + "\x00" + obj.Name))
		name += "_" + hex.EncodeToString(sum[:4])
	}
	return name + ".yaml"
}

// component is the kustomization.yaml of the component directory. The same
// type reads the file of an earlier run and writes the new one.
type component struct {
	APIVersion string           `json:"apiVersion"`
	Kind       string           `json:"kind"`
	Patches    []componentPatch `json:"patches"`
}

type componentPatch struct {
	Path string `json:"path"`
}

const (
	componentAPIVersion = "kustomize.config.k8s.io/v1alpha1"
	componentKind       = "Component"
)

// componentHeader is the comment at the top of a new list.
const componentHeader = KustomizeMarker + "\n" +
	"# A Kustomize component: each patch puts one workload in the RuntimeClass.\n" +
	"# To use it, add this directory to `components:` in the kustomization that must move.\n" +
	"# A later run adds entries at the end of this list and changes nothing else. You can\n" +
	"# remove an entry, or change the order. A run refuses a file that has more in it.\n"

// ComponentPaths reads a kustomization.yaml that an earlier run made, and
// returns the patch files that it lists, in the order of the file.
//
// It returns an error when the file is not one that a run can add to: it
// does not start with KustomizeMarker, or it has more in it than the list
// (another field, a comment between the entries, another layout). A run
// writes the list again from data, so what is not data would be lost; it is
// better to refuse the file.
func ComponentPaths(text []byte) ([]string, error) {
	_, paths, err := readComponent(text)
	return paths, err
}

// readComponent splits a list into its comment lines at the top and its
// entries.
func readComponent(text []byte) (head []byte, paths []string, err error) {
	if !bytes.HasPrefix(text, []byte(KustomizeMarker+"\n")) {
		return nil, nil, fmt.Errorf("it does not start with the line %q", KustomizeMarker)
	}
	body := text
	for len(body) > 0 && body[0] == '#' {
		end := bytes.IndexByte(body, '\n')
		if end < 0 {
			end = len(body) - 1
		}
		body = body[end+1:]
	}
	head = text[:len(text)-len(body)]

	var c component
	if err := yaml.UnmarshalStrict(body, &c); err != nil {
		return nil, nil, fmt.Errorf("it has more than the list of patches that agentmoat writes: %s", oneLine(err.Error()))
	}
	if c.APIVersion != componentAPIVersion || c.Kind != componentKind {
		return nil, nil, fmt.Errorf("it is not a %s of %s", componentKind, componentAPIVersion)
	}
	paths = make([]string, 0, len(c.Patches))
	for _, p := range c.Patches {
		if p.Path == "" {
			return nil, nil, fmt.Errorf("it has a patch with no path")
		}
		paths = append(paths, p.Path)
	}
	if !bytes.Equal(body, componentBody(paths)) {
		return nil, nil, fmt.Errorf("its list is not in the layout that agentmoat writes (a comment or a blank line in the list, other quotes, or another indent)")
	}
	return head, paths, nil
}

// componentBody is the YAML of a list, with no comment.
func componentBody(paths []string) []byte {
	c := component{APIVersion: componentAPIVersion, Kind: componentKind, Patches: make([]componentPatch, 0, len(paths))}
	for _, p := range paths {
		c.Patches = append(c.Patches, componentPatch{Path: p})
	}
	// The type has strings only, so the encoder cannot fail.
	body, _ := yaml.Marshal(c)
	return body
}

// ComponentAdd returns the text of the list with the paths of add in it.
//
// old is the list of an earlier run, or nil when there is none: the result
// is then a new list with its comment. With an old list, the paths that it
// does not have go at its end, sorted, and nothing else changes: the comment
// lines at the top and the entries stay as they are, so the diff of a run
// has added lines only. (One case has a changed line: an old list with no
// entry is `patches: []`.) A path that the list has already is not added a
// second time. added is the paths that are new in the result.
func ComponentAdd(old []byte, add []string) (text []byte, added []string, err error) {
	head, paths := []byte(componentHeader), []string(nil)
	if old != nil {
		if head, paths, err = readComponent(old); err != nil {
			return nil, nil, err
		}
	}
	have := make(map[string]bool, len(paths)+len(add))
	for _, p := range paths {
		have[p] = true
	}
	for _, p := range add {
		if !have[p] {
			have[p] = true
			added = append(added, p)
		}
	}
	if old != nil && len(added) == 0 {
		return old, nil, nil
	}
	sort.Strings(added)
	return append(append([]byte(nil), head...), componentBody(append(paths, added...))...), added, nil
}
